def p(text):
    return f"        <p>{html.escape(text)}</p>\n"


def h2(text):
    return f"        <h2>{html.escape(text)}</h2>\n"


def ul(items):
    out = ["        <ul>\n"]
    for item in items:
        out.append(f"          <li>{html.escape(item)}</li>\n")
    out.append("        </ul>\n")
    return "".join(out)


